if __name__ == '__main__':

    sample_context = [
        (
            'Retrieval-Augmented Generation (RAG) combines retrieval '
            'of relevant documents with text generation.'
        ),
        (
            'RAG retrieves relevant chunks before generating an answer.'
        ),
    ]

    sample_history = (
        'User: Explain RAG.\n'
        'Assistant: RAG combines retrieval and generation.'
    )

    question = 'Explain it in more detail.'

    answer = generate_answer(
        question=question,
        retrieved_docs=sample_context,
        history=sample_history,
    )

    print('Question:', question)
    print('Answer:', answer)